export function slugify(value) {
  return encodeURIComponent(value.trim().replace(/\s+/g, '-'));
}
export function getAllLessons(stage) {
  return (curriculum[stage]?.groups || []).flatMap((group, gi) => group.items.map((title, ii) => ({ title, group: group.title, stage, slug: `${stage}-${gi}-${ii}-${slugify(title)}` })));
}
export function findLesson(slug) {
  for (const stage of Object.keys(curriculum)) {
    const lesson = getAllLessons(stage).find(item => item.slug === slug);
    if (lesson) return lesson;
  }
  return null;
}
